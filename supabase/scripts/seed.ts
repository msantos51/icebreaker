// Builds supabase/seed.sql from the mission catalogue, after validating it.
// Usage: npm run seed:build -w @icebreaker/supabase
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { type Mission, validateCatalog } from '@icebreaker/core';

const ROOT = join(import.meta.dirname, '..');
export const CATALOG_PATH = join(ROOT, 'missions', 'catalog.pt-PT.json');
export const SEED_PATH = join(ROOT, 'seed.sql');

export function loadCatalog(): Mission[] {
  return JSON.parse(readFileSync(CATALOG_PATH, 'utf8')) as Mission[];
}

const literal = (value: string) => `'${value.replaceAll("'", "''")}'`;

export function buildSeedSql(missions: Mission[]): string {
  const rows = missions.map((m) =>
    [
      literal(m.id),
      `${literal(m.type)}::public.mission_type`,
      String(m.level),
      `array[${m.tags.map(literal).join(', ')}]::text[]`,
      literal(m.message_a),
      literal(m.message_b),
      literal(m.follow_up),
    ].join(', '),
  );
  const ids = missions.map((m) => literal(m.id)).join(', ');
  return `-- Generated by supabase/scripts/seed.ts from supabase/missions/catalog.pt-PT.json.
-- Do not edit by hand: edit the catalogue and run \`npm run seed:build -w @icebreaker/supabase\`.

insert into public.missions (id, type, level, tags, message_a, message_b, follow_up, active)
values
${rows.map((r) => `  (${r}, true)`).join(',\n')}
on conflict (id) do update set
  type = excluded.type,
  level = excluded.level,
  tags = excluded.tags,
  message_a = excluded.message_a,
  message_b = excluded.message_b,
  follow_up = excluded.follow_up,
  active = true;

-- Missions removed from the catalogue are deactivated, not deleted (mission_runs reference them).
update public.missions set active = false where id not in (${ids});
`;
}

if (import.meta.main) {
  const missions = loadCatalog();
  const problems = validateCatalog(missions);
  if (problems.length > 0) {
    console.error(problems.join('\n'));
    process.exit(1);
  }
  writeFileSync(SEED_PATH, buildSeedSql(missions));
  console.log(`Wrote ${missions.length} missions to ${SEED_PATH}`);
}
